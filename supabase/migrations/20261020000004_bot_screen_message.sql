-- Один экран на чат: id сообщения, которое бот переписывает.
--
-- Раньше бот мог нарисовать меню отдельным сообщением, а потом ещё
-- переписать старое сообщение — в чате меню оказывалось в двух местах
-- («антисимметрия»). Теперь у каждого чата ровно один экран: бот переписывает
-- его вместо новых сообщений.

ALTER TABLE public.bot_users
  ADD COLUMN IF NOT EXISTS screen_message_id BIGINT;
